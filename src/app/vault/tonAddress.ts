// Address derivation for legacy EXM accounts with Wallet V4R2 in workchain 0.
export function legacyTonAddress(publicKey: Uint8Array) {
  const code = Cell.fromBase64(WALLET_V4R2_CODE)
  if (code.hash().toString("hex") !== WALLET_V4R2_CODE_HASH) throw new Error("Invalid TON Wallet V4R2 code")
  const data = beginCell()
    .storeUint(0, 32)
    .storeUint(0x29a9a317, 32)
    .storeBuffer(Buffer.from(publicKey))
    .storeBit(false)
    .endCell()
  return contractAddress(0, { code, data }).toString({ testOnly: true, bounceable: false })
}
